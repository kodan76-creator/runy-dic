/** Текст-шапка для позиции руны (1–7) выбранной раскладки ('evaluation' | 'healing'). */
export function getPositionLabel(layoutType: string, position: number): string {
  const list = layoutType === 'healing' ? HEALING_POSITION_LABELS : EVALUATION_POSITION_LABELS
  return list[position - 1] ?? ''
}
