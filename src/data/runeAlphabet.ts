// Радо, Су = перев. Фаис-су, Урс = перев. Орс, Яй = перев. Йех, Ибо =
// перев. Хебо, Пре = перев. Так, Ща = перев. Ша, Эрэ = перев. Цэрэ,
// Нуль = перев. Амаюн.
// Поле `rune` у таких знаков — точное имя записи в runes.json
// («НАЗВАНИЕ (перевернутое положение)»), чтобы клик открывал описание.

export type RuneAlphabetLetter = {
  /** Название знака (как на листе) */
  name: string
  /** Звук/транскрипция в скобках на листе */
  sound: string
  /** Файл картинки знака в public/images/n_runy/runy/ */
  image: string
  /**
   * Точное имя записи в runes.json (только у знаков-перевёртышей,
   * чьё название на листе отличается от имени карточки каталога).
   */
  rune?: string
}

